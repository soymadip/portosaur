//go:build ignore

// Generator for emoji.go: the emoji shortcode table, from the
// same name data the build resolves `:smile:` against.
//
// remark-emoji resolves shortcodes through node-emoji, which
// looks names up in emojilib's `lib` table (emojis.json). This
// generator reads that file from the repo's node_modules and
// writes the sorted name-to-glyph table as emoji.go.
//
// Run with: go generate
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	source, err := findEmojilib()
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	var table map[string]struct {
		Char string `json:"char"`
	}
	if err := json.Unmarshal(raw, &table); err != nil {
		return err
	}
	names := make([]string, 0, len(table))
	for name, entry := range table {
		if entry.Char == "" {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	var out strings.Builder
	rel, err := filepath.Rel(".", source)
	if err != nil {
		rel = source
	}
	fmt.Fprintf(&out, "// Code generated by gen.go. DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Source: %s (%d entries), the name table\n", filepath.ToSlash(rel), len(names))
	fmt.Fprintf(&out, "// node-emoji looks up and remark-emoji resolves\n")
	fmt.Fprintf(&out, "// shortcodes against. Regenerate with: go generate\n")
	fmt.Fprintf(&out, "//go:generate go run gen.go\n\n")
	fmt.Fprintf(&out, "package main\n\n")
	fmt.Fprintf(&out, "// emojiShortcode is one `:name:` shortcode the build\n")
	fmt.Fprintf(&out, "// renders: its name and the glyph it becomes.\n")
	fmt.Fprintf(&out, "type emojiShortcode struct {\n\tname  string\n\tglyph string\n}\n\n")
	fmt.Fprintf(&out, "// emojiShortcodes is the full shortcode table,\n")
	fmt.Fprintf(&out, "// sorted by name.\n")
	fmt.Fprintf(&out, "var emojiShortcodes = []emojiShortcode{\n")
	for _, name := range names {
		fmt.Fprintf(&out, "\t{%q, %q},\n", name, table[name].Char)
	}
	fmt.Fprintf(&out, "}\n")
	return os.WriteFile("emoji.go", []byte(out.String()), 0o644)
}

// findEmojilib locates emojilib's emojis.json in the repo's
// node_modules: hoisted at the top level when the package
// manager puts it there, otherwise under bun's versioned
// `.bun` store (the highest version wins when several are
// installed).
func findEmojilib() (string, error) {
	hoisted := filepath.Join("..", "..", "node_modules", "emojilib", "emojis.json")
	if _, err := os.Stat(hoisted); err == nil {
		return hoisted, nil
	}
	matches, err := filepath.Glob(filepath.Join("..", "..", "node_modules", ".bun", "emojilib@*", "node_modules", "emojilib", "emojis.json"))
	if err != nil {
		return "", err
	}
	if len(matches) == 0 {
		return "", fmt.Errorf("emojilib emojis.json not found under ../../node_modules")
	}
	sort.Strings(matches)
	return matches[len(matches)-1], nil
}
