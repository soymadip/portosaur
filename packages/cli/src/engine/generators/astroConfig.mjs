import path from "node:path";
import fs from "node:fs";

/**
 * Thin Astro shim writer (Phase 2, D13).
 *
 * The CLI generates a minimal Astro project root in `.portosaur/`:
 * `astro.config.mjs` (site/base/outDir + the Portosaur integration with the
 * resolved options object embedded) and `src/content.config.ts` (content
 * collections whose glob loaders point outside the generated root at the
 * user's content dirs). Nothing else is generated — the integration owns
 * all build-time work.
 *
 * The functions here only build the file *contents* (pure string builders);
 * the runner (`writeAstroShim`) resolves the options and writes the files.
 */

/**
 * Builds the contents of the generated `.portosaur/astro.config.mjs`.
 *
 * @param {object} options - The resolved `PortosaurOptions` from `buildSiteConfig`.
 * @param {object} args - Generation arguments.
 * @param {string} args.projectDir - The user's project directory (absolute).
 * @param {string} args.outDir - The resolved output directory (absolute).
 * @param {number} args.mtime - The config.yml mtime (cache-busting comment).
 * @param {boolean} [args.minify=true] - Whether Vite should minify the build (`--no-minify`).
 * @param {boolean|string} [args.poll=false] - Polling for the dev watcher (`--poll [interval]`).
 * @returns {string} The `astro.config.mjs` file contents.
 */
export function buildAstroConfigContent(
  options,
  { projectDir, outDir, mtime, minify = true, poll = false },
) {
  const publicDir = path.resolve(projectDir, "static");

  // Vite overrides, only when the CLI flags ask for them.
  const viteBuild = minify
    ? ""
    : `
    build: {
      minify: false,
    },`;
  const viteServer =
    poll === false
      ? ""
      : `
    server: {
      watch: {
        usePolling: true${
          poll !== true && poll !== ""
            ? `,
        interval: ${JSON.stringify(Number(poll))}`
            : ""
        },
      },
    },`;
  const vite =
    viteBuild || viteServer
      ? `
  vite: {${viteBuild}${viteServer}
  },`
      : "";

  return `// Auto-generated by portosaur — do not edit
// Generated at: ${mtime}
import { defineConfig } from "astro/config";
import mdx from "@astrojs/mdx";
import preact from "@astrojs/preact";
import sitemap from "@astrojs/sitemap";
import portosaur from "@portosaur/theme";

const options = ${JSON.stringify(options, null, 2)};

export default defineConfig({
  site: ${JSON.stringify(options.site.url)},
  base: ${JSON.stringify(options.site.baseUrl)},
  trailingSlash: "always",
  outDir: ${JSON.stringify(outDir)},
  publicDir: ${JSON.stringify(publicDir)},
  build: {
    format: "directory",
  },${vite}
  integrations: [
    mdx(),
    preact(),
    sitemap(),
    portosaur(options),
  ],
});
`;
}

/**
 * Builds the contents of the generated `.portosaur/src/content.config.ts`.
 *
 * Two content collections, `notes` and `blog`, with glob loaders pointed at
 * the user's (configurable) content dirs. MDX-only (Q2): the pattern matches
 * `*.mdx` and nothing else. In docs mode the `notes` collection points at
 * the docs dir — `options.site.notesDir` is already mode-aware.
 *
 * When `<blogDir>/authors.yml` exists, a third `authors` data collection is
 * emitted (file loader over the YAML map; each key becomes an entry id).
 * The blog author pages resolve display names from it — the Docusaurus
 * blog plugin did the same, and the golden `/blog/authors/` pages list
 * names from this file even when the blog has no posts at all.
 *
 * @param {object} options - The resolved `PortosaurOptions` from `buildSiteConfig`.
 * @param {number} mtime - The config.yml mtime (cache-busting comment).
 * @param {string} projectDir - The user's project directory (absolute).
 * @returns {string} The `src/content.config.ts` file contents.
 */
export function buildContentConfigContent(options, mtime, projectDir) {
  const notesDir = options.site.notesDir;
  const blogDir = options.site.blogDir;

  const authorsFile = ["authors.yml", "authors.yaml"].find((name) =>
    fs.existsSync(path.join(projectDir, blogDir, name)),
  );

  const authorsImport = authorsFile ? `, file` : "";
  const authorsCollection = authorsFile
    ? `
const authors = defineCollection({
  loader: file(${JSON.stringify(`../${blogDir}/${authorsFile}`)}),
  schema: z.object({
    name: z.string(),
    title: z.string().optional(),
    url: z.string().optional(),
    image_url: z.string().optional(),
    email: z.string().optional(),
    page: z.boolean().optional(),
  }),
});
`
    : "";
  const authorsExport = authorsFile ? ", authors" : "";

  return `// Auto-generated by portosaur — do not edit
// Generated at: ${mtime}
import { defineCollection, z } from "astro:content";
import { glob${authorsImport} } from "astro/loaders";

// Frontmatter Portosaur understands (§4.15). Unknown keys are stripped.
const docSchema = z.object({
  title: z.string().optional(),
  description: z.string().optional(),
  icon: z.string().optional(),
  color: z.string().optional(),
  sidebar_position: z.number().optional(),
  sidebar_label: z.string().optional(),
  slug: z.string().optional(),
  topic_list: z.union([z.boolean(), z.record(z.string(), z.any())]).optional(),
  tags: z.array(z.string()).optional(),
  authors: z.array(z.union([z.string(), z.record(z.string(), z.any())])).optional(),
  image: z.string().optional(),
  pagination_label: z.string().optional(),
  id: z.string().optional(),
  date: z.coerce.date().optional(),
  draft: z.boolean().optional(),
});

const notes = defineCollection({
  loader: glob({
    pattern: "**/*.mdx",
    base: ${JSON.stringify(`../${notesDir}`)},
  }),
  schema: docSchema,
});

const blog = defineCollection({
  loader: glob({
    pattern: "**/*.mdx",
    base: ${JSON.stringify(`../${blogDir}`)},
  }),
  schema: docSchema,
});
${authorsCollection}
export const collections = { notes, blog${authorsExport} };
`;
}
