import fs from "node:fs";
import path from "node:path";

/** A logger with the methods the worker sync uses (all optional). */
export interface ServiceWorkerLogger {
  info?: (message: string) => void;
}

/**
 * Service worker generation — builds the hand-written `sw.js`
 * for a site and keeps it in sync with the generated root's
 * `public/`, so Next copies it into the static export.
 *
 * The worker is a plain string template, not a core module: the
 * CLI already generates every other runtime file this way, and
 * the only reason the favicon pipeline spawns core is sharp
 * (a 20MB native binary). Spawning a process for string
 * replacement would be silly.
 *
 * What the worker does: precache the shell (home, offline page,
 * icons, manifest), serve visited pages stale-while-revalidate,
 * serve the hashed app files under `/_next/static/` cache-first,
 * and fall back to the cached offline page for navigations that
 * fail. A new build takes over immediately (`skipWaiting` +
 * `clients.claim`) and drops the old caches.
 */

export interface ServiceWorkerSpec {
  /** The site's base path (`/` or `/porto-astro/`). */
  basePath: string;
  /** Build version, stamped into the cache names. */
  version: string;
}

const normalizeBase = (basePath: string): string =>
  basePath.endsWith("/") ? basePath : `${basePath}/`;

/** The shell: everything the worker precaches at install. */
export function serviceWorkerPrecache(basePath: string): string[] {
  const base = normalizeBase(basePath);
  return [
    base,
    `${base}offline/`,
    `${base}favicon/icon-192x192.png`,
    `${base}favicon/icon-512x512.png`,
    `${base}favicon/icon-maskable-512x512.png`,
    `${base}favicon/apple-touch-icon.png`,
    `${base}manifest.webmanifest`,
  ];
}

export function buildServiceWorkerContent(spec: ServiceWorkerSpec): string {
  const base = normalizeBase(spec.basePath);
  const precache = serviceWorkerPrecache(base);
  const list = precache.map((url) => `  "${url}",`).join("\n");
  return `// Auto-generated by portosaur — do not edit
// The PWA service worker. Hand-written, no library: precache
// the shell, stale-while-revalidate pages, cache-first for the
// hashed app files, offline fallback for failed navigations.
const VERSION = "${spec.version}";
const SHELL_CACHE = \`porto-shell-\${VERSION}\`;
const PAGES_CACHE = \`porto-pages-\${VERSION}\`;
const STATIC_CACHE = \`porto-static-\${VERSION}\`;
const STATIC_PREFIX = "${base}_next/static/";
const OFFLINE_URL = "${base}offline/";
const PRECACHE = [
${list}
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      // One file at a time: a missing icon must not fail the
      // whole install (a user-provided favicon dir may lack
      // files the manifest lists).
      for (const url of PRECACHE) {
        try {
          await cache.add(url);
        } catch {
          // A missing precache entry is not fatal.
        }
      }
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keep = new Set([SHELL_CACHE, PAGES_CACHE, STATIC_CACHE]);
      for (const name of await caches.keys()) {
        if (!keep.has(name)) {
          await caches.delete(name);
        }
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") {
    return;
  }
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) {
    return;
  }
  if (request.mode === "navigate") {
    event.respondWith(staleWhileRevalidate(request));
    return;
  }
  if (url.pathname.startsWith(STATIC_PREFIX)) {
    event.respondWith(cacheFirst(request));
  }
  // Everything else passes through to the network untouched.
});

async function staleWhileRevalidate(request) {
  const pages = await caches.open(PAGES_CACHE);
  const shell = await caches.open(SHELL_CACHE);
  const cached = (await pages.match(request)) ?? (await shell.match(request));
  // The network fetch starts now, so a cached page still
  // revalidates in the background.
  const network = fetch(request)
    .then(async (response) => {
      if (response.ok) {
        await pages.put(request, response.clone());
      }
      return response;
    })
    .catch(() => null);
  if (cached) {
    return cached;
  }
  return (await network) ?? (await shell.match(OFFLINE_URL)) ?? Response.error();
}

async function cacheFirst(request) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request);
  if (cached) {
    return cached;
  }
  try {
    const response = await fetch(request);
    if (response.ok) {
      await cache.put(request, response.clone());
    }
    return response;
  } catch {
    return Response.error();
  }
}
`;
}

/**
 * Keep `public/sw.js` in step with the PWA switch: write the
 * generated worker when enabled, remove a stale generated one
 * when disabled. A symlink is the user's own worker (linked by
 * the union) and is never touched either way.
 */
export async function syncServiceWorker({
  publicDir,
  enable,
  basePath,
  logger,
}: {
  publicDir: string;
  enable: boolean;
  basePath: string;
  logger?: ServiceWorkerLogger;
}): Promise<void> {
  const target = path.join(publicDir, "sw.js");
  try {
    if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) {
      logger?.info?.("Using the project's own sw.js — skipping generation.");
      return;
    }
  } catch {
    // Unreadable — fall through and let the write/remove below
    // report it.
  }
  if (!enable) {
    // Off means off: a stale worker would keep serving the old
    // site (the union never deletes real files, so this is the
    // only thing that clears it).
    fs.rmSync(target, { force: true });
    return;
  }
  // The version is the generation time, not the config mtime:
  // a content-only edit changes no config but must still ship
  // a new worker, or the precached home page goes stale.
  const content = buildServiceWorkerContent({
    basePath,
    version: String(Date.now()),
  });
  fs.mkdirSync(publicDir, { recursive: true });
  fs.writeFileSync(target, content);
}
